// TestEd25519SignVerifyRFC8032 verifies sign+verify against the RFC 8032 §5.1
// draft-josefsson-eddsa-ed25519-02 test vectors sourced from
// ~/wolfssl/wolfcrypt/test/test.c (sKey1/pKey1/sig1 …).
// Vector 1 uses an empty message, exercising the zero-length path.
func TestEd25519SignVerifyRFC8032(t *testing.T) {
	for i, v := range ed25519Vecs {
		var key Ed25519Key
		if ret := Wc_Ed25519Init(&key); ret != 0 {
			t.Fatalf("vec %d: Ed25519Init returned %d", i+1, ret)
		}
		defer Wc_Ed25519Free(&key)

		ret := Wc_Ed25519ImportPrivateKey(v.seed, len(v.seed), v.pub, len(v.pub), &key)
		if ret != 0 {
			t.Fatalf("vec %d: ImportPrivateKey returned %d", i+1, ret)
		}

		// Sign
		sig := make([]byte, ED25519_SIG_SIZE)
		sigSz := ED25519_SIG_SIZE
		ret = Wc_Ed25519SignMsg(&key, v.msg, len(v.msg), sig, &sigSz)
		if ret != 0 {
			t.Fatalf("vec %d: SignMsg returned %d", i+1, ret)
		}
		if sigSz != ED25519_SIG_SIZE {
			t.Fatalf("vec %d: unexpected sigSz %d", i+1, sigSz)
		}
		if !bytes.Equal(sig[:sigSz], v.sig) {
			t.Fatalf("vec %d: signature mismatch\n  got:  %x\n  want: %x", i+1, sig[:sigSz], v.sig)
		}

		// Verify with known-good signature
		var res int
		ret = Wc_Ed25519VerifyMsg(v.sig, len(v.sig), v.msg, len(v.msg), &res, &key)
		if ret != 0 {
			t.Fatalf("vec %d: VerifyMsg returned %d", i+1, ret)
		}
		if res != 1 {
			t.Fatalf("vec %d: VerifyMsg res=%d, want 1", i+1, res)
		}

		// Tampered signature must fail
		bad := make([]byte, len(v.sig))
		copy(bad, v.sig)
		bad[0] ^= 0xff
		res = 0
		ret = Wc_Ed25519VerifyMsg(bad, len(bad), v.msg, len(v.msg), &res, &key)
		if ret == 0 && res == 1 {
			t.Fatalf("vec %d: tampered signature verified (should fail)", i+1)
		}
	}
}

// TestEd25519ImportPublicVerifyRFC8032 verifies that verification works when
// only the public key is loaded (sign path is skipped).
func TestEd25519ImportPublicVerifyRFC8032(t *testing.T) {
	for i, v := range ed25519Vecs {
		var key Ed25519Key
		if ret := Wc_Ed25519Init(&key); ret != 0 {
			t.Fatalf("vec %d: Ed25519Init returned %d", i+1, ret)
		}
		defer Wc_Ed25519Free(&key)

		ret := Wc_Ed25519ImportPublic(v.pub, len(v.pub), &key)
		if ret != 0 {
			t.Fatalf("vec %d: ImportPublic returned %d", i+1, ret)
		}

		var res int
		ret = Wc_Ed25519VerifyMsg(v.sig, len(v.sig), v.msg, len(v.msg), &res, &key)
		if ret != 0 {
			t.Fatalf("vec %d: VerifyMsg returned %d", i+1, ret)
		}
		if res != 1 {
			t.Fatalf("vec %d: VerifyMsg res=%d, want 1", i+1, res)
		}
	}
}
